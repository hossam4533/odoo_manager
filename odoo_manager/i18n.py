def set_lang(lang: str) -> None:
    global LANG
    LANG = lang if lang in ("ar", "en") else "ar"


def tr(key: str, **kw) -> str:
    pair = S.get(key)
    if not pair:
        return key
    s = pair[0] if LANG == "ar" else pair[1]
    return s.format(**kw) if kw else s


def is_rtl() -> bool:
    return LANG == "ar"
